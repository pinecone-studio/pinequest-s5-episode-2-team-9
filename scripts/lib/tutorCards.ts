// The study-card texts the tutor needs, taken from the app's i18n files. /api is compiled on its own
// and cannot import src/, so scripts/build-tutor-cards.ts writes these into api/_lib/tutor/cards.ts.
import en from '../../src/i18n/en.json'
import mn from '../../src/i18n/mn.json'
import { TUTOR_MODELS } from '../../api/_lib/tutor/knowledge'
import { keys } from '../../src/models/ModelDefinition'
import { library } from '../../src/models/registry'

type Dict = Record<string, string>
const dicts: Record<'en' | 'mn', Dict> = { en, mn }

export interface CardText {
  name: string
  group: string
  desc: string
  fact: string
}

export interface TutorCard {
  /** The knowledge entry this part shares (e.g. ram_1 → ram). */
  info: string
  /** Part ids that must be in place before this one. */
  dependsOn: string[]
  en: CardText
  mn: CardText
}

export interface TutorModelCards {
  title: { en: string; mn: string }
  parts: Record<string, TutorCard>
}

export function buildTutorCards(): Record<string, TutorModelCards> {
  const out: Record<string, TutorModelCards> = {}
  for (const id of TUTOR_MODELS) {
    const def = library.find((m) => m.id === id)
    if (!def) throw new Error(`No model ${id}`)
    const text = (lang: 'en' | 'mn', key: string) => dicts[lang][key] ?? dicts.en[key] ?? ''
    const parts: Record<string, TutorCard> = {}
    for (const part of def.parts) {
      const card = (lang: 'en' | 'mn'): CardText => ({
        name: text(lang, keys.partName(def.id, part)),
        group: text(lang, keys.group(def.id, part.group)),
        desc: text(lang, keys.partDesc(def.id, part)),
        fact: text(lang, keys.partFact(def.id, part)),
      })
      parts[part.id] = {
        info: part.info ?? part.id,
        dependsOn: part.dependsOn,
        en: card('en'),
        mn: card('mn'),
      }
    }
    out[id] = { title: { en: text('en', keys.title(def.id)), mn: text('mn', keys.title(def.id)) }, parts }
  }
  return out
}

export const renderTutorCards = (cards: Record<string, TutorModelCards>) =>
  `// Generated by scripts/build-tutor-cards.ts from src/i18n. Do not edit; run \`npx tsx scripts/build-tutor-cards.ts\`.
import type { TutorModelId } from './knowledge.js'

export interface CardText {
  name: string
  group: string
  desc: string
  fact: string
}

export interface TutorCard {
  info: string
  dependsOn: string[]
  en: CardText
  mn: CardText
}

export const cards: Record<TutorModelId, { title: { en: string; mn: string }; parts: Record<string, TutorCard> }> = ${JSON.stringify(cards, null, 2)}
`
